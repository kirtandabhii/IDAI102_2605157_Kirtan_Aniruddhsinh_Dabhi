def _build():
    brands = []
    for name, domain, countries, types, kind, greener in _RAW:
        brands.append({
            "name": name,
            "domain": domain,
            "countries": countries.split(),
            "types": types.split(),
            "kind": kind,
            "greener": greener,
        })
    return brands


BRANDS = _build()
BY_NAME = {b["name"].lower(): b for b in BRANDS}
DOMAINS = {b["domain"] for b in BRANDS}


def lookup(name):
    """Find a brand by name (case-insensitive, tolerant of extra words)."""
    if not name:
        return None
    text = name.strip().lower()
    if text in BY_NAME:
        return BY_NAME[text]
    # "Veja trainers" or "zara.com" still match the brand.
    best = None
    for key, brand in BY_NAME.items():
        if len(key) > 3 and (text.startswith(key + " ") or text == brand["domain"]):
            if best is None or len(key) > len(best["name"]):
                best = brand
    return best


def is_ethical_brand(name):
    """True if the brand is on the greener list."""
    brand = lookup(name)
    return bool(brand and brand["greener"])


def brand_card(name):
    """The small dictionary the UI needs to show a brand's logo."""
    brand = lookup(name)
    if not brand:
        return None
    return {"name": brand["name"], "domain": brand["domain"], "kind": brand["kind"],
            "greener": brand["greener"], "logo": f"/api/logo/{brand['domain']}"}


def brands_for(type_id, greener_only=False):
    """Brands that sell this product type."""
    return [b for b in BRANDS if type_id in b["types"] and (b["greener"] or not greener_only)]


def greener_names(type_id, limit=5):
    """Greener brands for a product type, then generic ideas (e.g. 'a cobbler resole')."""
    names = [b["name"] for b in brands_for(type_id, greener_only=True)]
    names += PRODUCT_TYPES.get(type_id, {}).get("ideas", [])
    if not names:  # nothing greener exists — any brand that sells it will do
        names = [b["name"] for b in brands_for(type_id)]
    return names[:limit]


